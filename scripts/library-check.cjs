const assert = require('node:assert/strict');
const fs = require('node:fs');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const {parseCubeCSV,cubeSource,normalizeName,validateCube,makeCards} = require('../cube-library');

const csv = '\uFEFFname,Type,Color,Rarity,board,Quantity,Notes\r\n"Bilbo Baggins, Burglar // Take a Glance",Creature,U,common,mainboard,2,"A comma, and a\nnewline"\r\n"Bilbo Baggins, Burglar",Creature,U,common,mainboard,1,\r\nStone Rain,Sorcery,R,uncommon,mainboard,1,\r\nForest,Basic Land,,common,mainboard,1,\r\nBlack Lotus,Artifact,,rare,maybeboard,1,\r\nIsland,Basic Land,,common,basics,30,\r\n';
assert.deepEqual(parseCubeCSV(csv).map(c => [c.name,c.quantity,c.color]),[['Bilbo Baggins, Burglar',3,'blue'],['Stone Rain',1,'red'],['Forest',1,'lands']]);
assert.equal(normalizeName('  Bilbo Baggins, Burglar // Take a Glance '),'bilbo baggins, burglar');
assert.equal(normalizeName('Ajani’s Pridemate'),normalizeName("Ajani's Pridemate"));
assert.throws(() => parseCubeCSV('Card Name,Quantity\nForest,1'),/Collection CSVs/);
assert.throws(() => parseCubeCSV(csv+'"Unfinished'),/unfinished quoted/);
assert.throws(() => parseCubeCSV(csv.replace('mainboard,2','mainboard,-2')),/quantity/);
assert.throws(() => parseCubeCSV(csv.replace('mainboard,2','mainboard,5001')),/5,000/);
assert.equal(cubeSource('https://cubecobra.com/cube/about/my-cube?view=table').download,'https://cubecobra.com/cube/download/csv/my-cube');
assert.throws(() => cubeSource('https://evil.example/cube/list/foo'));
assert.throws(() => cubeSource('javascript:alert(1)'));
const hobbit = validateCube(JSON.parse(fs.readFileSync(new URL('../data/hobbit.json',`file://${__filename}`),'utf8')));
assert.equal(hobbit.cards.length,130);
assert.equal(makeCards(hobbit).length,180);
assert.equal(new Set(makeCards(hobbit).map(c => c.id)).size,180);

(async () => {
  const browser = await chromium.launch({headless:true,channel:process.env.BROWSER_CHANNEL || 'chrome'});
  try {
    const context = await browser.newContext({viewport:{width:1600,height:1000}});
    const page = await context.newPage(), errors = [];
    page.on('pageerror',error => errors.push(error.message));
    const url = process.env.CUBE_URL || 'http://127.0.0.1:8766';
    const ready = async p => p.locator('.card').first().waitFor({state:'attached'});
    await page.goto(url); await ready(page);
    assert.equal(await page.locator('#cube-select option').count(),3);
    await page.getByRole('checkbox',{name:'Include Felidar Cub',exact:true}).check();
    await page.selectOption('#cube-select','hobbit');
    assert.equal(await page.locator('.card').count(),180);
    assert.equal(await page.locator('.card input:checked').count(),0);
    const importCollection = async text => {
      await page.locator('#owned-file').setInputFiles({name:'collection.csv',mimeType:'text/csv',buffer:Buffer.from(text)});
      await page.waitForFunction(() => document.querySelector('#owned-file').value === '');
    };
    await importCollection('English Name,Quantity\n"Bilbo Baggins, Burglar // Take a Glance",1\n');
    assert.match(await page.locator('#ownership-status').textContent(),/1 of 180 copies owned/);
    const importCube = async name => {
      await page.locator('#import-cube').click();
      await page.locator('#cube-url').fill('https://cubecobra.com/cube/about/test-cube');
      await page.locator('#prepare-cube').click();
      assert.equal(await page.locator('#cube-export').getAttribute('href'),'https://cubecobra.com/cube/download/csv/test-cube');
      await page.locator('#cube-file').setInputFiles({name:'cube.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
      await page.waitForFunction(() => document.querySelector('#cube-csv').value.includes('Stone Rain'));
      await page.locator('#cube-name').fill(name);
      await page.locator('#preview-cube').click();
      assert.match(await page.locator('#cube-preview-summary').textContent(),/5 mainboard copies · 3 card names/);
      await page.locator('#save-cube').click();
      assert.equal(await page.locator('#page-title').textContent(),name);
      assert.equal(await page.locator('.card').count(),5);
      return page.locator('#cube-select').inputValue();
    };
    const custom = await importCube('Adventure cube');
    await page.locator('[data-mode="buy"]').click();
    const acquire = copy => page.getByRole('checkbox',{name:`Acquire Bilbo Baggins, Burglar, copy ${copy} of 3`,exact:true});
    assert.equal(await acquire(1).isDisabled(),true,'Imported copies are covered');
    assert.equal(await acquire(2).isChecked(),false);
    await acquire(3).check();
    assert.match(await page.locator('#work-summary').textContent(),/2 \/ 5 covered · 3 to buy · 0 organized/);
    await acquire(3).uncheck();
    assert.match(await page.locator('#work-summary').textContent(),/1 \/ 5 covered/);
    await acquire(3).check();
    await page.locator('[data-mode="organize"]').click();
    assert.equal(await page.locator('.card input:checked').count(),0,'Purchases never organize cards');
    await page.getByRole('checkbox',{name:'Include Bilbo Baggins, Burglar, copy 3 of 3',exact:true}).check();
    assert.match(await page.locator('#work-summary').textContent(),/2 \/ 5 covered · 3 to buy · 1 organized/);
    await importCollection('English Name,Quantity\n"Bilbo Baggins, Burglar // Take a Glance",2\n');
    assert.match(await page.locator('#work-summary').textContent(),/2 \/ 5 covered · 3 to buy · 1 organized/,'New collection overlaps purchases instead of adding them again');
    await page.locator('#buy-list').click();
    assert.equal(await page.locator('#buy-text').inputValue(),'1 Bilbo Baggins, Burglar\n1 Forest\n1 Stone Rain');
    await page.locator('#close-buy').click();
    await page.reload(); await ready(page);
    assert.equal(await page.locator('#cube-select').inputValue(),custom);
    assert.equal(await page.locator('.card input:checked').count(),1);
    const second = await context.newPage(); await second.goto(url); await ready(second);
    await page.locator('[data-mode="buy"]').click(); await acquire(2).check();
    await second.waitForFunction(() => document.querySelector('#work-summary').textContent.includes('3 / 5 covered'));
    await second.close();
    const other = await importCube('Separate cube');
    assert.notEqual(other,custom);
    assert.match(await page.locator('#work-summary').textContent(),/2 \/ 5 covered · 3 to buy · 0 organized/,'Same names in a new cube have independent checkmarks');
    await page.selectOption('#cube-select','original');
    await page.locator('[data-mode="organize"]').click();
    assert.equal(await page.getByRole('checkbox',{name:'Include Felidar Cub',exact:true}).isChecked(),true,'Original progress survives imports');
    await page.selectOption('#cube-select',custom);
    await page.locator('#import-cube').click();
    await page.locator('#cube-name').fill('Broken');
    await page.locator('#cube-dialog summary').click();
    await page.locator('#cube-csv').fill('Card Name,Quantity\nForest,1');
    await page.locator('#preview-cube').click();
    assert.equal(await page.locator('#save-cube').isDisabled(),true);
    assert.match(await page.locator('#cube-import-status').textContent(),/Collection CSVs/);
    await page.locator('#close-cube').click();
    assert.equal(await page.locator('#cube-select option').count(),5);
    const downloadPromise = page.waitForEvent('download'); await page.locator('#backup').click();
    const download = await downloadPromise, backup = JSON.parse(fs.readFileSync(await download.path(),'utf8'));
    assert.equal(backup.version,2); assert.equal(backup.library.cubes.length,2);
    assert(backup.library.acquired.length >= 3);
    const fresh = await browser.newContext(); const restored = await fresh.newPage(); await restored.goto(url); await ready(restored);
    restored.once('dialog',dialog => dialog.accept());
    await restored.locator('#restore-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
    await restored.waitForFunction(() => document.querySelectorAll('#cube-select option').length === 5);
    await restored.selectOption('#cube-select',custom);
    assert.match(await restored.locator('#work-summary').textContent(),/3 \/ 5 covered · 2 to buy · 1 organized/);
    await restored.locator('[data-mode="buy"]').click();
    await restored.locator('[data-filter="missing"]').click();
    assert.equal(await restored.locator('.card:visible').count(),2);
    await restored.locator('input[data-card]:visible').first().focus(); await restored.keyboard.press('Space');
    assert.equal(await restored.locator('.card:visible').count(),1,'Keyboard purchase updates remaining filter');
    await restored.reload(); await ready(restored);
    assert.match(await restored.locator('#work-summary').textContent(),/4 \/ 5 covered/);
    await page.selectOption('#cube-select','hobbit');
    for(const width of [320,390,768,1280,1600]) {
      await page.setViewportSize({width,height:1000});
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),`No overflow at ${width}`);
      await page.locator('#import-cube').click();
      assert(await page.evaluate(() => document.querySelector('#cube-dialog').getBoundingClientRect().right <= innerWidth));
      await page.locator('#close-cube').click();
    }
    const borders = await page.locator('.column').evaluateAll(nodes => nodes.filter(node => !node.hidden).every(node => parseFloat(getComputedStyle(node).borderInlineStartWidth) >= 1));
    assert(borders,'Desktop columns have explicit borders');
    assert.deepEqual(errors,[]);
    console.log('PASS: CSV mainboard imports, duplicates, adventure names, defaults, invalid imports, independent buying/organizing, ownership overlap, persistence, cross-tab sync, complete backup/restore, keyboard flow and responsive bordered layout.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
